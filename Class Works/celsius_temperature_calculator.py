
temperature_in_celsius = input("Enter the temperature in celsius: ")

temperature_in_farenheit = (float(temperature_in_celsius) * 1.8 ) + 32


temperature_in_kelvin = float(temperature_in_celsius) + 273.15


print("The temperature equivalent in farenheit is: ", temperature_in_farenheit)
print("The temperature equivalent in kelvin is: ",temperature_in_kelvin)
